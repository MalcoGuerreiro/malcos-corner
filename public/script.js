function translateNowPlayingStatus(status) {
  if (status === 'now playing') return t('nowPlaying.statusNow');
  if (status === 'last played') return t('nowPlaying.statusLast');
  return status;
}

function translateRecommendationMessage(message) {
  const messageMap = {
    'recommendation sent :)': 'recommendation.sent',
    'wait a little before sending again :)': 'recommendation.cooldown',
    'fill the song first :)': 'recommendation.fillSong',
    'recommendations are not configured yet :(': 'recommendation.notConfigured',
    'couldn’t send it :(\ntry again in a bit.': 'recommendation.failedLong',
    "couldn't send it :(\ntry again in a bit.": 'recommendation.failedLong'
  };

  const key = messageMap[message];
  return key ? t(key) : message;
}

async function fetchNowPlaying() {
  const container = document.querySelector('#now-playing');
  if (!container) return;

  try {
    const response = await fetch('/api/lastfm/now-playing');
    const data = await response.json();

    if (!data.ok && data.configured === false) {
      container.innerHTML = `
        <div class="album-cover placeholder-cover">?</div>
        <div>
          <p class="track-status">${escapeHtml(t('nowPlaying.idle'))}</p>
          <p class="track-name">${escapeHtml(t('nowPlaying.notConfigured'))}</p>
          <p class="track-artist">${escapeHtml(t('nowPlaying.addEnv'))}</p>
        </div>
      `;
      return;
    }

    if (!data.ok) throw new Error(data.message || 'Last.fm error');

    if (!data.hasTrack || !data.nowPlaying) {
      clearNowPlayingProgress();
      container.innerHTML = `
        <div class="album-cover placeholder-cover">?</div>
        <div>
          <p class="track-status">${escapeHtml(t('nowPlaying.idle'))}</p>
          <p class="track-name">${escapeHtml(t('nowPlaying.nothing'))}</p>
          <p class="track-artist">${escapeHtml(t('nowPlaying.silence'))}</p>
        </div>
      `;
      return;
    }

    const coverMarkup = data.cover
      ? `<img class="album-cover" src="${escapeHtml(data.cover)}" alt="${escapeHtml(t('nowPlaying.albumAlt'))}">`
      : `<div class="album-cover placeholder-cover">${escapeHtml(t('nowPlaying.noCover'))}</div>`;

    const durationMs = Number(data.durationMs) || 0;
    const trackKey = `${data.artist || ''}::${data.name || ''}`;

    if (durationMs > 0 && nowPlayingProgress.key !== trackKey) {
      setNowPlayingProgress(trackKey, durationMs);
    } else if (durationMs > 0) {
      nowPlayingProgress.durationMs = durationMs;
    }

    const progressMarkup = durationMs > 0
      ? `
        <div class="track-progress" aria-label="estimated song progress">
          <div class="track-progress-rail">
            <span id="track-progress-bar" class="track-progress-bar"></span>
          </div>
          <div class="track-progress-times">
            <span id="track-progress-elapsed">0:00</span>
            <span id="track-progress-duration">${formatTrackTime(durationMs)}</span>
          </div>
        </div>
      `
      : '';

    container.innerHTML = `
      ${coverMarkup}
      <div class="track-copy">
        <p class="track-status">${escapeHtml(translateNowPlayingStatus(data.status))}</p>
        <p class="track-name">${escapeHtml(data.name)}</p>
        <p class="track-artist">${escapeHtml(data.artist)}</p>
        ${progressMarkup}
      </div>
    `;

    updateNowPlayingProgress();
  } catch (error) {
    clearNowPlayingProgress();
    container.innerHTML = `
      <div class="album-cover placeholder-cover">:(</div>
      <div>
        <p class="track-status">${escapeHtml(t('nowPlaying.error'))}</p>
        <p class="track-name">${escapeHtml(t('nowPlaying.errorSong'))}</p>
        <p class="track-artist">${escapeHtml(t('nowPlaying.tryAgain'))}</p>
      </div>
    `;
  }
}

async function submitRecommendation(event) {
  event.preventDefault();
  playClick();

  const formData = new FormData(recommendationForm);
  const payload = Object.fromEntries(formData.entries());
  const song = String(payload.artist_song || '').trim();

  if (!song) {
    recommendationMessage.textContent = t('recommendation.fillSong');
    return;
  }

  recommendationMessage.textContent = t('recommendation.wait');

  try {
    const response = await fetch('/api/recommendations', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });

    const data = await response.json();
    recommendationMessage.textContent = data.message
      ? translateRecommendationMessage(data.message)
      : (response.ok ? t('recommendation.sent') : t('recommendation.failed'));

    if (response.ok) recommendationForm.reset();
  } catch (error) {
    recommendationMessage.textContent = t('recommendation.failedLong');
  }
}

function updateClock() {
  const now = new Date();
  const isPortuguese = state.language === 'pt';
  const locale = isPortuguese ? 'pt-BR' : 'en-US';
  const time = now.toLocaleTimeString(locale, {
    hour: '2-digit',
    minute: '2-digit',
    hour12: !isPortuguese
  });
  const weekday = now.toLocaleDateString(locale, { weekday: 'short' }).replace('.', '');
  const day = String(now.getDate()).padStart(2, '0');
  const month = String(now.getMonth() + 1).padStart(2, '0');

  document.querySelector('#clock-time').textContent = time;
  document.querySelector('#clock-date').textContent = `${weekday} ${day}/${month}`;
}

